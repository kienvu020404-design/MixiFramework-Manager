"""Generate immutable UI metadata ahead of time instead of parsing JSON at startup."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
fields=json.loads((root/'app/src/main/assets/catalog.json').read_text(encoding='utf-8'))
def string(value):return json.dumps(value,ensure_ascii=False).replace('$','\\$')
def strings(values):return 'listOf('+','.join(map(string,values))+')'
rows=[]
for f in fields:
 rows.append('        Option('+','.join([string(f['page']),string(f['key']),string(f['title']),string(f['kind']),string(f['initial']),str(f['min']),str(f['max']),string(f['unit']),strings(f['labels']),strings(f['values']),str(f['secret']).lower()])+'),')
text='package com.mixi.manager\n\n// Generated by scripts/generate_catalog.py; edit catalog.json, then regenerate.\ninternal object UiCatalog {\n    val options:List<Option> = listOf(\n'+'\n'.join(rows)+'\n    )\n}\n'
(root/'app/src/main/kotlin/com/mixi/manager/UiCatalog.kt').write_text(text,encoding='utf-8')
print('COMPILED_UI_CATALOG_GENERATED',len(fields))
